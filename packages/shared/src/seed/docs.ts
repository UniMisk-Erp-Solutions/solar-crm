const cell = (s: string): string => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

/** docs/VERIFY_BEFORE_RELYING.md — generated from the same list that seeds the verify_register table. */
export function renderVerifyDoc(): string {
  const rows = VERIFY_ITEMS.map((v) => `| ${v.code} | ${cell(v.title)} | ${cell(v.detail)} | ${cell(v.where_to_check)} | ${v.confidence} | open |`);
  return `# Verify before relying

Every legal or policy value in this system comes from a research report dated 26-Oct-2026 whose sources were mostly trade press. The items below are **open**: they are either unverified, conflicting between sources, or inferred. Each is also seeded into the \`verify_register\` table (Admin → Verify register), where a compliance officer records the closing source URL and date.

Rules that depend on an open item are stored in \`rule_config\` with status \`unverified\` or \`conflicting\`; they are advisory only (a warning, never a hard stop) until a compliance officer verifies and activates them.

_Generated by \`npm run seed:sql\` from \`packages/shared/src/seed/ref.verify.ts\`. Codes V-1 … V-25 follow "India solar distributor CRM blueprint.md" §10a; V-26 was added by the seed._

| Code | Item | What is unverified | Where to check | Confidence | Status |
|---|---|---|---|---|---|
${rows.join('\n')}
`;
}

