/**
 * Generates docs/RULES.md from the seeded rule_config rows, so the documentation can never drift from what the database receives.
 *   npm run docs:rules
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildRuleConfigRows } from '@solar/shared/seed';

const rows = buildRuleConfigRows(new Date('2026-10-26T06:30:00Z'));
const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
const val = (v: unknown) => { const s = JSON.stringify(v); return s.length > 70 ? `${s.slice(0, 67)}…` : s; };

const byCat = new Map<string, typeof rows>();
for (const r of rows) byCat.set(r.category, [...(byCat.get(r.category) ?? []), r]);

const active = rows.filter((r) => r.is_active).length;
const verified = rows.filter((r) => r.status === 'verified' && r.is_active).length;
const conflicting = rows.filter((r) => r.status === 'conflicting').length;

const out: string[] = [];
out.push('# Rule configuration (generated)', '');
out.push('> Generated by `npm run docs:rules` from the seed. **Do not edit by hand.** The live values are in the `rule_config` table and are edited in *Admin & rules → Rule configuration*.', '');
out.push('## How rules behave', '');
out.push('* Rules are **versioned by `effective_from`**; the engine resolves the version in force on the reference date (commissioning date for compliance gates, quote date for pricing, today for SLAs).');
out.push('* A rule that is **not `verified`, or not active, is advisory only**: it can produce a warning but never blocks a transaction, unless a Compliance Officer explicitly activates it as a hard stop (`enforce_hard_stop`).');
out.push('* Every gate result stores the `rule_config` ids it used so the decision can be reproduced.');
out.push('* Every change needs a **source name and source reference** and is audited.', '');
out.push(`Seeded: **${rows.length}** rule versions in **${byCat.size}** categories — ${active} active (${verified} verified and active), ${conflicting} conflicting. Items not in this table (channel margins, credit days, conversion rates) are hypotheses and are deliberately never coded.`, '');

for (const [cat, list] of [...byCat.entries()].sort(([a], [b]) => a.localeCompare(b))) {
  out.push(`## \`${cat}\``, '');
  out.push('| Key | Value | Effective from | Status | Confidence | Active | Max severity | Source |', '|---|---|---|---|---|---|---|---|');
  for (const r of list.sort((a, b) => a.key.localeCompare(b.key) || a.effective_from.localeCompare(b.effective_from))) {
    out.push(`| \`${esc(r.key)}\` | \`${esc(val(r.value))}\` | ${r.effective_from}${r.effective_to ? ` → ${r.effective_to}` : ''} | ${r.status} | ${r.confidence} | ${r.is_active ? 'yes' : 'no'} | ${r.max_severity} | ${esc(r.source_name)} |`);
  }
  out.push('');
}
writeFileSync(join(process.cwd(), 'docs', 'RULES.md'), out.join('\n'));
console.log(`docs/RULES.md written: ${rows.length} rules`);
